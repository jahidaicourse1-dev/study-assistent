export function validateTopicInput(topic: string): string | null {
  const trimmed = topic.trim();
  if (!trimmed) {
    return 'Please enter a topic or question before generating.';
  }
  if (trimmed.length < 2) {
    return 'Please enter at least 2 characters so the AI can understand your topic.';
  }
  if (trimmed.length > 5000) {
    return 'Topic text is too long. Please keep it under 5,000 characters.';
  }
  return null;
}

export function clampPrecisionValue(value: number): number {
  if (!Number.isFinite(value)) {
    return DEFAULT_AI_SETTINGS.precision;
  }
  const clamped = Math.min(0.7, Math.max(0.2, value));
  return Math.round(clamped * 100) / 100;
}

export function mapPrecisionToThinkingLevel(precision: number): 'LOW' | 'MEDIUM' | 'HIGH' {
  const safe = clampPrecisionValue(precision);
  if (safe <= 0.35) {
    return 'HIGH';
  }
  if (safe <= 0.55) {
    return 'MEDIUM';
  }
  return 'LOW';
}

export function describePrecisionMode(precision: number): string {
  const safe = clampPrecisionValue(precision);
  if (safe <= 0.35) {
    return 'Exam-Exact & Analytical';
  }
  if (safe <= 0.55) {
    return 'Balanced Clarity & Analogy';
  }
  return 'Creative & Analogy-Rich';
}

export function detectBengaliScript(text: string): boolean {
  return /[\u0980-\u09FF]/.test(text);
}

export function resolveOutputLanguage(
  preference: LanguagePreference,
  inputText: string
): 'en' | 'bn' {
  if (preference === 'bn') return 'bn';
  if (preference === 'en') return 'en';
  return detectBengaliScript(inputText) ? 'bn' : 'en';
}

export function sanitizeSettings(raw: Partial<AISettings> | null | undefined): AISettings {
  const validModels: SupportedGeminiModel[] = ['gemini-4-hydrogen', 'gemini-3.1-flash-lite'];
  const validLangs: LanguagePreference[] = ['auto', 'en', 'bn'];
  const validLevels: StudentLevel[] = [
    'Beginner',
    'Secondary (SSC)',
    'Higher Secondary (HSC)',
    'University / Job Preparation',
  ];

  return {
    model: raw?.model && validModels.includes(raw.model) ? raw.model : DEFAULT_AI_SETTINGS.model,
    precision:
      typeof raw?.precision === 'number'
        ? clampPrecisionValue(raw.precision)
        : DEFAULT_AI_SETTINGS.precision,
    defaultLanguage:
      raw?.defaultLanguage && validLangs.includes(raw.defaultLanguage)
        ? raw.defaultLanguage
        : DEFAULT_AI_SETTINGS.defaultLanguage,
    defaultLevel:
      raw?.defaultLevel && validLevels.includes(raw.defaultLevel)
        ? raw.defaultLevel
        : DEFAULT_AI_SETTINGS.defaultLevel,
  };
}

export function buildMarkdownNotes(
  explanation: StudyExplanation,
  meta: { subject: Subject | string; level: StudentLevel | string; style: ExplanationStyle | string }
): string {
  const lines: string[] = [
    `# ${explanation.title}`,
    '',
    `- **Subject:** ${meta.subject}`,
    `- **Student Level:** ${meta.level}`,
    `- **Study Style:** ${meta.style}`,
    `- **Generated by:** EduGenius AI (Apex Edutech Labs)`,
    '',
    '## 1. Concept Definition',
    explanation.conceptDefinition,
    '',
    '## 2. Real-World Analogy',
    explanation.realWorldAnalogy,
    '',
    '## 3. Practical Examples',
    ...explanation.practicalExamples.map((ex, idx) => `${idx + 1}. ${ex}`),
    '',
    '## Important Key Points',
    ...explanation.keyPoints.map((pt) => `- ${pt}`),
    '',
    '## Summary',
    explanation.summary,
  ];

  if (explanation.flashcards && explanation.flashcards.length > 0) {
    lines.push('', '## Flashcards');
    explanation.flashcards.forEach((card, idx) => {
      lines.push(`- **Q${idx + 1}:** ${card.front}`, `  - **A:** ${card.back}`);
    });
  }

  return lines.join('\n');
}

export function buildPlainTextNotes(explanation: StudyExplanation): string {
  const sections = [
    explanation.title,
    '',
    `Concept Definition:\n${explanation.conceptDefinition}`,
    `Real-World Analogy:\n${explanation.realWorldAnalogy}`,
    `Practical Examples:\n${explanation.practicalExamples.map((e, i) => `${i + 1}. ${e}`).join('\n')}`,
    `Important Key Points:\n${explanation.keyPoints.map((k) => `• ${k}`).join('\n')}`,
    `Summary:\n${explanation.summary}`,
  ];
  return sections.join('\n\n');
}
